-- Flyway V1: esquema do dominio Rede Frio. H2 em arquivo; nada de ddl-auto=create.
CREATE TABLE instituicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    cidade VARCHAR(80) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    contato VARCHAR(120),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_instituicao_tipo CHECK (tipo IN ('DOADORA','RECEPTORA','AMBAS'))
);

CREATE TABLE refrigerador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    instituicao_id BIGINT NOT NULL,
    temp_min_c DECIMAL(5,2) NOT NULL,
    temp_max_c DECIMAL(5,2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_refrigerador_instituicao FOREIGN KEY (instituicao_id) REFERENCES instituicao(id),
    CONSTRAINT ck_refrigerador_faixa CHECK (temp_min_c < temp_max_c)
);

CREATE TABLE lote_alimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(160) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    quantidade_kg DECIMAL(10,2) NOT NULL,
    validade DATE NOT NULL,
    instituicao_origem_id BIGINT NOT NULL,
    situacao VARCHAR(25) NOT NULL DEFAULT 'DISPONIVEL',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lote_origem FOREIGN KEY (instituicao_origem_id) REFERENCES instituicao(id),
    CONSTRAINT ck_lote_quantidade CHECK (quantidade_kg >= 0),
    CONSTRAINT ck_lote_situacao CHECK (situacao IN ('DISPONIVEL','ESGOTADO'))
);

CREATE TABLE doacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    instituicao_destino_id BIGINT NOT NULL,
    quantidade_kg DECIMAL(10,2) NOT NULL,
    status VARCHAR(25) NOT NULL DEFAULT 'PENDENTE',
    criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_doacao_lote FOREIGN KEY (lote_id) REFERENCES lote_alimento(id),
    CONSTRAINT fk_doacao_destino FOREIGN KEY (instituicao_destino_id) REFERENCES instituicao(id),
    CONSTRAINT ck_doacao_quantidade CHECK (quantidade_kg > 0),
    CONSTRAINT ck_doacao_status CHECK (status IN ('PENDENTE','CONFIRMADA','CANCELADA'))
);

CREATE TABLE leitura_temperatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refrigerador_id BIGINT NOT NULL,
    temperatura_c DECIMAL(5,2) NOT NULL,
    registrada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_leitura_refrigerador FOREIGN KEY (refrigerador_id) REFERENCES refrigerador(id)
);

CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refrigerador_id BIGINT NOT NULL,
    leitura_id BIGINT NOT NULL UNIQUE,
    mensagem VARCHAR(250) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolvido_em TIMESTAMP,
    CONSTRAINT fk_alerta_refrigerador FOREIGN KEY (refrigerador_id) REFERENCES refrigerador(id),
    CONSTRAINT fk_alerta_leitura FOREIGN KEY (leitura_id) REFERENCES leitura_temperatura(id),
    CONSTRAINT ck_alerta_status CHECK (status IN ('ABERTO','RESOLVIDO'))
);
